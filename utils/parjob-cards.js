// 转换数据格式为统一格式
function formatUserData(user, dataSource = 'mock') {
  return {
    _id: user._id,
    user_id: user.user_id,
    nickname: user.nickname,
    avatar: user.avatar || '/static/images/user-bg.png',
    gender: user.gender,
    age: user.age,
    education: user.education,
    city: user.location_text && user.location_text.length > 0 
      ? user.location_text[user.location_text.length - 1] 
      : user.city || '',
    location: user.location || [],
    location_text: user.location_text || [],
    skills: user.skills || [],
    categorie_tags: user.categorie_tags || [],
    strengths: user.strengths,
    photos: user.photos || ['/static/images/user-bg.png'],
    show_fields: user.show_fields,
    isOnline: true,
    dataSource: dataSource // 'mock' 或 'cloud'
  }
}

// 融合 mock 数据和云函数数据
async function mergeUserData(mockUsers, cloudUsers) {
  const allUsers = []
  const existingUserIds = new Set()
  
  // 先添加云函数数据
  cloudUsers.forEach(user => {
    const formattedUser = formatUserData(user, 'cloud')
    allUsers.push(formattedUser)
    existingUserIds.add(user.user_id)
  })
  
  // 再添加 mock 数据（避免重复）
  mockUsers.forEach(user => {
    if (!existingUserIds.has(user.user_id)) {
      const formattedUser = formatUserData(user, 'mock')
      allUsers.push(formattedUser)
    }
  })
  
  return allUsers
}

// 筛选用户数据的通用函数
function filterUsers(users, filters) {
  return users.filter(user => {
    // 性别筛选
    if (filters.gender !== undefined && filters.gender !== '' && user.gender !== filters.gender) {
      return false
    }

    // 年龄筛选
    if (filters.ageRange) {
      const userAge = Number.parseInt(user.age)
      if (userAge < filters.ageRange.min || userAge > filters.ageRange.max) {
        return false
      }
    }

    // 技能筛选
    if (filters.skills && filters.skills.length > 0) {
      const userSkills = user.skills || []
      const hasMatchingSkill = filters.skills.some(skill => userSkills.includes(skill))
      if (!hasMatchingSkill) {
        return false
      }
    }

    // 擅长领域筛选
    if (filters.categorieTags && filters.categorieTags.length > 0) {
      const userCategorieTags = user.categorie_tags || []
      const hasMatchingCategory = filters.categorieTags.some(tag => userCategorieTags.includes(tag))
      if (!hasMatchingCategory) {
        return false
      }
    }

    // 自定义技能筛选
    if (filters.customSkills && filters.customSkills.length > 0) {
      const userCustomSkills = user.custom_skills || []
      const hasMatchingCustomSkill = filters.customSkills.some(skill => userCustomSkills.includes(skill))
      if (!hasMatchingCustomSkill) {
        return false
      }
    }

    // 城市筛选
    if (filters.city && filters.city.length > 0) {
      const userCity = user.city
      const userLocationText = user.location_text
      
      // 检查用户城市是否匹配
      let cityMatched = false
      
      // 直接匹配城市名
      if (userCity && filters.city.includes(userCity)) {
        cityMatched = true
      }
      
      // 检查用户的位置信息是否包含目标城市
      if (!cityMatched && userLocationText && Array.isArray(userLocationText)) {
        for (const targetCity of filters.city) {
          if (userLocationText.includes(targetCity)) {
            cityMatched = true
            break
          }
        }
      }
      
      // 如果用户有市级信息，检查是否匹配目标城市
      if (!cityMatched && userCity) {
        for (const targetCity of filters.city) {
          // 如果目标城市是区级，尝试匹配用户所在市级
          if (targetCity.endsWith('区') || targetCity.endsWith('县')) {
            // 从用户的位置信息中找到对应的市级
            const userCityLevel = userLocationText?.find(loc => 
              loc.endsWith('市') && !loc.endsWith('区') && !loc.endsWith('县')
            )
            if (userCityLevel && userCityLevel === userCity) {
              cityMatched = true
              break
            }
          }
        }
      }
      
      if (!cityMatched) {
        return false
      }
    }

    return true
  })
}

// 根据筛选条件获取趴活卡片（支持多种数据模式 mock-cloud full-mock 和 full-cloud ）
export async function getFilteredParjobCards(filters = {}, mode = 'mock-cloud') {
  let mockUsers = []
  let cloudUsers = []
  
  // 根据模式获取数据
  if (mode === 'full-mock' || mode === 'mock-cloud') {
    // 获取 mock 数据
    mockUsers = getActiveParjobCards()
    
    // 对 mock 数据进行筛选
    mockUsers = filterUsers(mockUsers, filters)
  }
  
  if (mode === 'full-cloud' || mode === 'mock-cloud') {
    // 获取云函数数据
    cloudUsers = await getCloudActiveParjobCards()
    
    // 对云函数数据进行筛选
    cloudUsers = filterUsers(cloudUsers, filters)
  }
  
  // 根据模式返回数据
  if (mode === 'full-mock') {
    return mockUsers.map(user => formatUserData(user, 'mock'))
  } else if (mode === 'full-cloud') {
    return cloudUsers.map(user => formatUserData(user, 'cloud'))
  } else {
    // mock-cloud 模式：融合数据
    return await mergeUserData(mockUsers, cloudUsers)
  }
}

// 获取所有活跃用户数据（支持多种模式）
export async function getAllActiveParjobCards(mode = 'mock-cloud') {
  return await getFilteredParjobCards({}, mode)
}

// 实时更新用户数据（添加或移除单个用户）
export function updateActiveUserInList(userList, userData, action = 'add') {
  const updatedList = [...userList]
  
  if (action === 'add') {
    // 添加用户：检查是否已存在，如果存在则更新，否则添加
    const existingIndex = updatedList.findIndex(user => user.user_id === userData.user_id)
    if (existingIndex === -1) {
      // 添加新用户
      updatedList.push(formatUserData(userData, 'cloud'))
    } else {
      // 更新现有用户数据
      updatedList[existingIndex] = formatUserData(userData, 'cloud')
    }
  } else if (action === 'remove') {
    // 移除用户：根据 user_id 移除
    const removeIndex = updatedList.findIndex(user => user.user_id === userData.user_id)
    if (removeIndex !== -1) {
      updatedList.splice(removeIndex, 1)
    }
  }
  
  return updatedList
}

