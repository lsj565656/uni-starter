// 获取所有可用的技能标签
export function getAvailableSkills() {
  const skills = new Set()
  for (const card of parjobCards) {
    for (const skill of card.skills) skills.add(skill)
  }
  return [...skills].sort()
}

// 获取所有可用的领域标签
export function getAvailableCategorieTags() {
  const categorie_tags = new Set()
  for (const card of parjobCards) {
    for (const categorie_tag of card.categorie_tags) categorie_tags.add(categorie_tag)
  }
  return [...categorie_tags].sort()
}

