// 获取所有活跃的趴活卡片
export function getActiveParjobCards() {
  return parjobCards.filter(card => card.is_active)
}

// 根据筛选条件获取趴活卡片
export function getFilteredParjobCards(filters = {}) {
  let filtered = getActiveParjobCards()

  if (filters.city && filters.city.length > 0) {
    filtered = filtered.filter(card => filters.city.includes(card.city))
  }

  if (filters.gender) {
    if (filters.gender === 'unknown') {
      // 未知性别：除了male和female之外的所有情况
      filtered = filtered.filter(card => !card.gender || (card.gender !== 'male' && card.gender !== 'female'))
    } else {
      filtered = filtered.filter(card => card.gender === filters.gender)
    }
  }

  if (filters.skills && filters.skills.length > 0) {
    filtered = filtered.filter(card => card.skills.some(skill => filters.skills.includes(skill)))
  }

  if (filters.ageRange) {
    filtered = filtered.filter(card => card.age >= filters.ageRange.min && card.age <= filters.ageRange.max)
  }

  return filtered
}

// 获取所有可用的城市列表
export function getAvailableCities() {
  const cities = [...new Set(parjobCards.map(card => card.city))]
  const fixedCities = ['郑州', '开封', '洛阳']
  const allCities = [...new Set([...cities, ...fixedCities])]
  return allCities.sort()
}

// 获取所有可用的技能标签
export function getAvailableSkills() {
  const skills = new Set()
  for (const card of parjobCards) {
    for (const skill of card.skills) skills.add(skill)
  }
  return [...skills].sort()
}

// 获取所有可用的领域标签
export function getAvailableTags() {
  const tags = new Set()
  for (const card of parjobCards) {
    for (const tag of card.tags) tags.add(tag)
  }
  return [...tags].sort()
}

// 根据用户ID获取趴活卡片
export function getParjobCardByUserId(userId) {
  return parjobCards.find(card => card.user_id === userId)
}

// 生成随机位置（用于星球分布）
export function generateRandomPosition() {
  return {
    x: Math.random() * 100, // 5-95%
    y: Math.random() * 100, // 5-95%
    z: Math.random() * 10 // 0-10 (深度)
  }
}

// 为每个卡片添加随机位置
export function addRandomPositions(cards) {
  return cards.map(card => ({
    ...card,
    position: generateRandomPosition()
  }))
}
